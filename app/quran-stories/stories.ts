export function getStoryVideoSearchUrl(
  story: Pick<QuranStory, "titleAr" | "titleEn">,
  language: "ar" | "en",
) {
  const query = language === "ar"
    ? `${story.titleAr} قصة بدون تجسيد الأنبياء نور فقط`
    : `${story.titleEn} story no depiction of prophets light only`;
  return `https://www.youtube.com/results?search_query=${encodeURIComponent(query)}`;
}

